"""Paired statistics between runs (plan: O5, T2).

Reads the per-question CSVs written by pub.aggregate_runs and compares each variant with a
base run on the questions both answered:
  * EX difference with a paired bootstrap 95% CI and an exact McNemar test;
  * Holm-Bonferroni adjustment across all variants compared with the same base;
  * differences in linking recall/precision and tokens per question (paired bootstrap).

Usage:
  python -m pub.stats                                  # base bird_dev_v18_k1_ref vs all bird_dev_v18_k1_* runs
  python -m pub.stats --base bird_dev_v18_k1_ref --variants bird_dev_v18_k1_no_rbp bird_dev_v18_k1_topn20
  python -m pub.stats --pairs bird_dev_full:bird_dev_v18_full
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any, Dict, List, Optional

from pub.common import (
    RESULTS_DIR, fmt_pct, holm_adjust, mcnemar_exact, md_table, paired_bootstrap_diff, read_csv,
    write_csv,
)

DEFAULT_BASE = "bird_dev_v18_k1_ref"
METRICS = (
    ("linked_table_recall", "Δ linked table recall"),
    ("linked_column_recall", "Δ linked column recall"),
    ("linked_column_precision", "Δ linked column precision"),
    ("prompt_column_recall", "Δ prompt column recall"),
    ("prompt_column_precision", "Δ prompt column precision"),
    ("prompt_columns", "Δ prompt columns"),
    ("tokens_total", "Δ tokens/question"),
    ("tokens_linking", "Δ linking tokens/question"),
)


def _load(results: Path, run: str) -> Dict[str, Dict[str, str]]:
    path = results / "per_question" / f"{run}.csv"
    if not path.exists():
        raise FileNotFoundError(f"{path} not found; run `python -m pub.aggregate_runs` first")
    return {row["instance_id"]: row for row in read_csv(path)}


def _float(value: str) -> Optional[float]:
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def compare(results: Path, base: str, variant: str) -> Dict[str, Any]:
    left, right = _load(results, base), _load(results, variant)
    shared = sorted(set(left) & set(right))
    a = [left[key]["correct"] == "True" for key in shared]
    b = [right[key]["correct"] == "True" for key in shared]
    diff, low, high = paired_bootstrap_diff([float(value) for value in a], [float(value) for value in b])
    test = mcnemar_exact(a, b)
    row: Dict[str, Any] = {
        "base": base, "variant": variant, "questions": len(shared),
        "only_in_base": len(set(left) - set(right)), "only_in_variant": len(set(right) - set(left)),
        "ex_base": sum(a) / len(a) if a else 0.0, "ex_variant": sum(b) / len(b) if b else 0.0,
        "ex_diff": diff, "ex_diff_ci_low": low, "ex_diff_ci_high": high,
        "base_only_correct": test["only_a"], "variant_only_correct": test["only_b"],
        "mcnemar_p": test["p_value"],
    }
    for key, _ in METRICS:
        pairs = [(_float(left[k].get(key)), _float(right[k].get(key))) for k in shared]
        pairs = [(x, y) for x, y in pairs if x is not None and y is not None]
        if not pairs:
            continue
        mean_base = sum(x for x, _ in pairs) / len(pairs)
        delta, delta_low, delta_high = paired_bootstrap_diff([x for x, _ in pairs], [y for _, y in pairs])
        row[f"{key}_base"] = mean_base
        row[f"{key}_diff"] = delta
        row[f"{key}_diff_ci_low"] = delta_low
        row[f"{key}_diff_ci_high"] = delta_high
        if key.startswith("tokens") and mean_base:
            row[f"{key}_diff_pct"] = delta / mean_base
    return row


def render_markdown(rows: List[Dict[str, Any]]) -> str:
    table = []
    for row in rows:
        tokens_pct = row.get("tokens_total_diff_pct")
        table.append({
            "Base → variant": f"{row['base']} → {row['variant']}",
            "n": row["questions"],
            "EX base → variant": f"{fmt_pct(row['ex_base'])} → {fmt_pct(row['ex_variant'])}",
            "ΔEX pts [95% CI]": f"{100 * row['ex_diff']:+.2f} [{100 * row['ex_diff_ci_low']:+.2f}, {100 * row['ex_diff_ci_high']:+.2f}]",
            "McNemar p": f"{row['mcnemar_p']:.4f}",
            "Holm p": f"{row['mcnemar_p_holm']:.4f}" if "mcnemar_p_holm" in row else "—",
            "Δ col recall pts": f"{100 * row['linked_column_recall_diff']:+.2f}" if "linked_column_recall_diff" in row else "—",
            "Δ prompt col prec pts": f"{100 * row['prompt_column_precision_diff']:+.2f}" if "prompt_column_precision_diff" in row else "—",
            "Δ tokens/q": f"{row['tokens_total_diff']:+,.0f} ({100 * tokens_pct:+.1f}%)" if tokens_pct is not None else "—",
        })
    columns = list(table[0].keys()) if table else []
    return ("# Paired comparisons\n\nGenerated by `python -m pub.stats`. Differences are variant minus base on the "
            "questions both runs contain. CIs are paired bootstrap (10,000 resamples); McNemar is exact; Holm "
            "adjusts across all variants compared with the same base.\n\n" + md_table(table, columns) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results", type=Path, default=RESULTS_DIR)
    parser.add_argument("--base", default=DEFAULT_BASE)
    parser.add_argument("--variants", nargs="*")
    parser.add_argument("--pairs", nargs="*", default=[], help="Extra base:variant pairs, compared without Holm")
    parser.add_argument("--output-name", default="comparisons")
    args = parser.parse_args()

    per_question = args.results / "per_question"
    variants = args.variants
    if variants is None:
        prefix = args.base.rsplit("_", 1)[0] + "_" if args.base.endswith("_ref") else args.base + "_"
        variants = sorted(path.stem for path in per_question.glob(f"{prefix}*.csv") if path.stem != args.base)

    rows: List[Dict[str, Any]] = []
    if (per_question / f"{args.base}.csv").exists() and variants:
        family = [compare(args.results, args.base, variant) for variant in variants]
        adjusted = holm_adjust({row["variant"]: row["mcnemar_p"] for row in family})
        for row in family:
            row["mcnemar_p_holm"] = adjusted[row["variant"]]
        rows.extend(family)
    else:
        print(f"No family comparison: base {args.base} or variants missing")
    for pair in args.pairs:
        base, variant = pair.split(":", 1)
        if (per_question / f"{base}.csv").exists() and (per_question / f"{variant}.csv").exists():
            rows.append(compare(args.results, base, variant))
        else:
            print(f"Skipping pair {pair}: per-question file missing")

    write_csv(args.results / f"{args.output_name}.csv", rows)
    (args.results / f"{args.output_name}.md").write_text(render_markdown(rows), encoding="utf-8")
    for row in rows:
        print(f"{row['base']} -> {row['variant']}: ΔEX {100 * row['ex_diff']:+.2f} pts "
              f"[{100 * row['ex_diff_ci_low']:+.2f}, {100 * row['ex_diff_ci_high']:+.2f}], McNemar p={row['mcnemar_p']:.4f}")
    print(f"Wrote {args.results / (args.output_name + '.csv')}")


if __name__ == "__main__":
    main()
