"""Diagnose the old 178-question Spider 2.0-Lite ablation (plan: O4).

The old ablation cannot be re-scored offline (per-question results need warehouse access), so
this script only checks whether each variant actually ran: how many instances got a final
selection, how many selections failed for every candidate, and the reported score and
denominator. A variant where most selections failed measures a pipeline failure, not the
removed component, and must not be reported as a component effect.

Usage:
  python -m pub.old_ablation
"""

from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from pathlib import Path

from pub.common import RESULTS_DIR, RUN_DIR, md_table, read_text_any, write_csv

VARIANTS = {
    "full (reference)": "log_subset_diverse_20_evaluation_slayql_ccase",
    "no_itee": "ablation1_no_itee",
    "no_rbp": "ablation1_no_rbp",
    "no_bm25": "ablation1_no_bm25",
    "no_qoc": "ablation1_no_qoc",
}
EXPECTED = 178


def diagnose(label: str, folder: str) -> dict:
    root = RUN_DIR / folder
    row = {"variant": label, "folder": folder, "exists": root.exists()}
    if not root.exists():
        return row
    path = root / "eval_result.txt"
    text = read_text_any(path) if path.exists() else ""
    match = re.search(r"Results:\s*(\d+)/(\d+)", text)
    row["reported_correct"] = int(match.group(1)) if match else None
    row["reported_denominator"] = int(match.group(2)) if match else None
    statuses = Counter()
    for selection in (root / "sql_selection").glob("*.jsonl"):
        for line in selection.read_text(encoding="utf-8", errors="replace").splitlines():
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            statuses[record.get("fallback") or record.get("status") or "unknown"] += 1
    row["selection_records"] = sum(statuses.values())
    row["all_candidates_failed"] = statuses.get("all_failed", 0)
    row["selection_statuses"] = json.dumps(dict(statuses))
    row["schema_prompts"] = len(list((root / "final_schema_prompts").glob("*.txt")))
    row["revision_ran"] = (root / "sql_revise").exists()
    failed_share = row["all_candidates_failed"] / row["selection_records"] if row["selection_records"] else None
    row["failed_share"] = failed_share
    row["verdict"] = ("pipeline failure: do not report as a component effect"
                      if (failed_share is not None and failed_share > 0.5) or (row["reported_denominator"] or EXPECTED) < 0.8 * EXPECTED
                      else "ran; denominator differs from reference" if row["reported_denominator"] not in (None, EXPECTED)
                      else "ran")
    return row


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, default=RESULTS_DIR)
    args = parser.parse_args()
    rows = [diagnose(label, folder) for label, folder in VARIANTS.items()]
    write_csv(args.output / "old_ablation_diagnosis.csv", rows)
    table = [{"Variant": row["variant"], "Reported": f"{row.get('reported_correct')}/{row.get('reported_denominator')}",
              "Selections": row.get("selection_records"), "All candidates failed": row.get("all_candidates_failed"),
              "Revision ran": row.get("revision_ran"), "Verdict": row.get("verdict", "missing")} for row in rows]
    (args.output / "old_ablation_diagnosis.md").write_text(
        "# Old 178-question ablation: diagnosis\n\nGenerated by `python -m pub.old_ablation`.\n\n"
        + md_table(table, list(table[0].keys())) + "\n", encoding="utf-8")
    for row in table:
        print(row)


if __name__ == "__main__":
    main()
