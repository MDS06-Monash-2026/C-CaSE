"""When does IT-EE actually reduce the exploration budget? (plan: O7)

For each run with initial_candidates.json this reports:
  * the retrieval-entropy distribution that IT-EE thresholds;
  * the budget IT-EE actually assigned (dynamic_t_max) and the completion turns used;
  * an offline simulation of it_ee.determine_budget at several thresholds, which shows how many
    questions would get the reduced budget and how many are forced to the full budget by the
    ComplexityAnalyzer keyword override (no API calls needed).

Usage:
  python -m pub.itee_activation --runs bird_dev_v18_full log_spider2_full_slayql
"""

from __future__ import annotations

import argparse
import contextlib
import io
from collections import Counter
from pathlib import Path
from typing import Any, Dict, List

from pub.common import RESULTS_DIR, RUN_DIR, md_table, read_json, write_csv

DEFAULT_RUNS = ("bird_dev_v18_full", "log_spider2_full_slayql", "spider1_test_full_3cand")
THRESHOLDS = (0.4, 0.7, 0.9, 0.95, 0.98, 0.99, 0.995, 1.01)
FULL_BUDGET = 10


def _quantile(ordered: List[float], fraction: float) -> float:
    return ordered[int(fraction * (len(ordered) - 1))] if ordered else float("nan")


def analyse_run(run_root: Path) -> Dict[str, Any]:
    import it_ee

    initial = read_json(run_root / "initial_candidates.json")
    entries = [value for value in initial.values() if value.get("entropy") is not None]
    entropies = sorted(float(value["entropy"]) for value in entries)
    assigned = Counter(value.get("dynamic_t_max") for value in entries)
    turns = []
    for instance_id in initial:
        path = run_root / "tool_calls" / f"{instance_id}.json"
        if path.exists():
            try:
                payload = read_json(path)
                turns.append(sum(1 for key in payload if str(key).startswith("turn_")))
            except (OSError, ValueError):
                pass
    result: Dict[str, Any] = {
        "run": run_root.name, "questions": len(entries),
        "entropy_min": entropies[0] if entropies else None,
        "entropy_p10": _quantile(entropies, 0.10), "entropy_p50": _quantile(entropies, 0.50),
        "entropy_p90": _quantile(entropies, 0.90),
        "entropy_max": entropies[-1] if entropies else None,
        "assigned_full_budget": assigned.get(FULL_BUDGET, 0),
        "assigned_reduced_budget": sum(count for budget, count in assigned.items() if budget is not None and budget < FULL_BUDGET),
        "questions_with_turn_logs": len(turns),
        "mean_turns_used": sum(turns) / len(turns) if turns else None,
    }
    with contextlib.redirect_stdout(io.StringIO()):
        for threshold in THRESHOLDS:
            reduced = 0
            for value in entries:
                _, budget = it_ee.determine_budget(float(value["entropy"]), query=value.get("question", ""),
                                                   base_turns=FULL_BUDGET, threshold=threshold)
                reduced += budget < FULL_BUDGET
            result[f"reduced_at_{threshold}"] = reduced
    # Above the maximum entropy every question is eligible, so anything still at full budget is the override.
    result["forced_by_complexity_override"] = len(entries) - result[f"reduced_at_{THRESHOLDS[-1]}"]
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", nargs="*")
    parser.add_argument("--output", type=Path, default=RESULTS_DIR)
    args = parser.parse_args()
    names = args.runs or list(DEFAULT_RUNS) + sorted(path.name for path in RUN_DIR.glob("bird_dev_v18_k1_*"))
    rows = []
    for name in names:
        run_root = RUN_DIR / name
        if not (run_root / "initial_candidates.json").exists():
            print(f"Skipping {name}: no initial_candidates.json")
            continue
        row = analyse_run(run_root)
        rows.append(row)
        print(f"{name}: entropy {row['entropy_min']:.4f}-{row['entropy_max']:.4f}, "
              f"reduced budget at default 0.4: {row['reduced_at_0.4']}/{row['questions']}, "
              f"forced full by override: {row['forced_by_complexity_override']}")
    write_csv(args.output / "itee_activation.csv", rows)
    table = []
    for row in rows:
        entry = {"Run": row["run"], "n": row["questions"],
                 "Entropy min / p50 / max": f"{row['entropy_min']:.3f} / {row['entropy_p50']:.3f} / {row['entropy_max']:.3f}",
                 "Assigned reduced budget": row["assigned_reduced_budget"],
                 "Forced full (override)": row["forced_by_complexity_override"]}
        for threshold in THRESHOLDS:
            entry[f"Reduced @{threshold}"] = row[f"reduced_at_{threshold}"]
        table.append(entry)
    (args.output / "itee_activation.md").write_text(
        "# IT-EE activation\n\nGenerated by `python -m pub.itee_activation`. \"Reduced @t\" is the number of questions "
        "that would get the reduced (safe-exit) budget at entropy threshold t, simulated offline with "
        "`it_ee.determine_budget`. The default threshold is 0.4.\n\n"
        + md_table(table, list(table[0].keys()) if table else []) + "\n", encoding="utf-8")
    print(f"Wrote {args.output / 'itee_activation.csv'}")


if __name__ == "__main__":
    main()
