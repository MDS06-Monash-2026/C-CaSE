"""Accuracy as a function of the number of SQL candidates (plan: O3, F3).

For runs with several candidates, and for j = 1..k:
  * oracle@j: at least one of the first j candidates is correct (upper bound for a perfect selector);
  * vote@j:   the most common execution result among the first j candidates is correct
              (ties go to the group containing the lowest candidate index).
The selected EX of the run (its real selector with all k candidates) is reported alongside.

Candidate results are read the same way evaluate_dataset.py reads them (generation results,
overridden by revision results for the same index), and correctness comes from
evaluation/<id>.json ("correct_candidate_ids").

Usage:
  python -m pub.oracle_at_k --runs bird_dev_full bird_dev_v18_full
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
from typing import Any, Dict, List, Optional

from pub.common import RESULTS_DIR, RUN_DIR, fmt_pct, md_table, read_json, write_csv

DEFAULT_RUNS = ("bird_dev_full", "bird_dev_v18_full", "spider1_test_full_3cand")


def _signature(frame) -> Optional[str]:
    try:
        rows = sorted(tuple(str(value) for value in row) for row in frame.astype(str).itertuples(index=False))
    except Exception:
        return None
    return hashlib.sha1(repr(rows).encode("utf-8", errors="replace")).hexdigest()


def _candidate_count(run_root: Path) -> int:
    config_path = run_root / "resolved_config.json"
    if config_path.exists():
        count = read_json(config_path).get("num_candidates")
        if count:
            return int(count)
    return len(list((run_root / "sql_gen").glob("r1_lite_execution_result_*")))


def analyse_run(run_root: Path) -> List[Dict[str, Any]]:
    from evaluate_dataset import _candidate_frames

    k = _candidate_count(run_root)
    records = read_json(run_root / "dataset.json")
    oracle = [0] * (k + 1)
    vote = [0] * (k + 1)
    selected = 0
    total = 0
    for instance_id in sorted(records):
        evaluation_path = run_root / "evaluation" / f"{instance_id}.json"
        if not evaluation_path.exists():
            continue
        evaluation = read_json(evaluation_path)
        total += 1
        selected += bool(evaluation.get("correct"))
        correct_ids = {int(value) for value in evaluation.get("correct_candidate_ids", [])}
        frames = {index: frame for index, frame in _candidate_frames(run_root, instance_id) if index < k}
        signatures = {index: _signature(frame) for index, frame in frames.items()}
        for j in range(1, k + 1):
            if any(index < j for index in correct_ids):
                oracle[j] += 1
            groups: Dict[str, List[int]] = {}
            for index in range(j):
                signature = signatures.get(index)
                if signature is not None:
                    groups.setdefault(signature, []).append(index)
            if groups:
                winner = max(groups.values(), key=lambda members: (len(members), -min(members)))
                if min(winner) in correct_ids:
                    vote[j] += 1
    rows = []
    for j in range(1, k + 1):
        rows.append({
            "run": run_root.name, "k_available": k, "j": j, "questions": total,
            "oracle_at_j": oracle[j] / total if total else 0.0,
            "vote_at_j": vote[j] / total if total else 0.0,
            "selected_ex_all_k": selected / total if total else 0.0,
        })
    return rows


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", nargs="*", default=list(DEFAULT_RUNS))
    parser.add_argument("--output", type=Path, default=RESULTS_DIR)
    args = parser.parse_args()
    rows: List[Dict[str, Any]] = []
    for name in args.runs:
        run_root = RUN_DIR / name
        if not (run_root / "evaluation").exists():
            print(f"Skipping {name}: no evaluation folder")
            continue
        if _candidate_count(run_root) < 2:
            print(f"Skipping {name}: fewer than 2 candidates")
            continue
        print(f"Candidate curve for {name} ...", flush=True)
        run_rows = analyse_run(run_root)
        rows.extend(run_rows)
        for row in run_rows:
            print(f"  j={row['j']}: oracle {row['oracle_at_j']:.4f}, vote {row['vote_at_j']:.4f}")
    write_csv(args.output / "oracle_at_k.csv", rows)
    table = [{"Run": row["run"], "k": row["j"], "n": row["questions"], "oracle@k %": fmt_pct(row["oracle_at_j"]),
              "vote@k %": fmt_pct(row["vote_at_j"]), "Selected EX (all k) %": fmt_pct(row["selected_ex_all_k"])}
             for row in rows]
    (args.output / "oracle_at_k.md").write_text(
        "# Accuracy vs number of candidates\n\nGenerated by `python -m pub.oracle_at_k`.\n\n"
        + md_table(table, list(table[0].keys()) if table else []) + "\n", encoding="utf-8")
    print(f"Wrote {args.output / 'oracle_at_k.csv'}")


if __name__ == "__main__":
    main()
